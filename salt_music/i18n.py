    if key in _TOOL_OF and "cmd" not in kw:
        from .tools import install_hint

        kw["cmd"] = install_hint(_TOOL_OF[key])
    if not kw:
        return text
    try:
        return text.format(**kw)
    except (KeyError, IndexError, ValueError):
        return text
